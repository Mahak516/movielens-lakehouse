-- =====================================================================================
-- 04_star_schema.sql  |  Dimensional model in MOVIELENS.CORE
--
--   FACT_RATINGS  grain = one row per (user, movie): the user's latest rating
--   DIM_USER      MovieLens has no user attributes, so the dimension holds activity bounds
--   DIM_MOVIE     title, release year (SCD type 1: changes overwrite)
--   DIM_GENRE  +  BRIDGE_MOVIE_GENRE   many-to-many between movies and genres
--   DIM_DATE      generated calendar, 1995-01-01 .. 2045-12-31
--
-- PRIMARY KEY / FOREIGN KEY constraints in Snowflake are informational (not enforced),
-- but they document the model and are used by BI tools. Integrity is enforced by the
-- load logic and by the checks in 06_data_quality.sql.
-- =====================================================================================

USE WAREHOUSE MOVIELENS_WH;
USE DATABASE MOVIELENS;

-- ---------- DDL ----------------------------------------------------------------------

CREATE OR REPLACE TABLE MOVIELENS.CORE.DIM_DATE (
  DATE_KEY      NUMBER(8,0)  NOT NULL,   -- yyyymmdd
  FULL_DATE     DATE         NOT NULL,
  CAL_YEAR      NUMBER(4,0),
  CAL_QUARTER   NUMBER(1,0),
  CAL_MONTH     NUMBER(2,0),
  MONTH_NAME    STRING,
  DAY_OF_MONTH  NUMBER(2,0),
  DAY_OF_WEEK   NUMBER(1,0),             -- ISO: 1 = Monday .. 7 = Sunday
  DAY_NAME      STRING,
  IS_WEEKEND    BOOLEAN,
  PRIMARY KEY (DATE_KEY)
);

CREATE TABLE IF NOT EXISTS MOVIELENS.CORE.DIM_MOVIE (
  MOVIE_KEY     NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
  MOVIE_ID      NUMBER(10,0) NOT NULL,   -- natural key from the source
  TITLE         STRING       NOT NULL,
  RELEASE_YEAR  NUMBER(4,0),
  UPDATED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (MOVIE_KEY),
  UNIQUE (MOVIE_ID)
);

CREATE TABLE IF NOT EXISTS MOVIELENS.CORE.DIM_GENRE (
  GENRE_KEY   NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
  GENRE_NAME  STRING NOT NULL,
  PRIMARY KEY (GENRE_KEY),
  UNIQUE (GENRE_NAME)
);

CREATE TABLE IF NOT EXISTS MOVIELENS.CORE.BRIDGE_MOVIE_GENRE (
  MOVIE_KEY  NUMBER(38,0) NOT NULL,
  GENRE_KEY  NUMBER(38,0) NOT NULL,
  PRIMARY KEY (MOVIE_KEY, GENRE_KEY),
  FOREIGN KEY (MOVIE_KEY) REFERENCES MOVIELENS.CORE.DIM_MOVIE (MOVIE_KEY),
  FOREIGN KEY (GENRE_KEY) REFERENCES MOVIELENS.CORE.DIM_GENRE (GENRE_KEY)
);

CREATE TABLE IF NOT EXISTS MOVIELENS.CORE.DIM_USER (
  USER_KEY         NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
  USER_ID          NUMBER(10,0) NOT NULL,
  FIRST_RATED_AT   TIMESTAMP_NTZ,
  LAST_RATED_AT    TIMESTAMP_NTZ,
  PRIMARY KEY (USER_KEY),
  UNIQUE (USER_ID)
);

CREATE TABLE IF NOT EXISTS MOVIELENS.CORE.FACT_RATINGS (
  USER_KEY   NUMBER(38,0) NOT NULL,
  MOVIE_KEY  NUMBER(38,0) NOT NULL,
  DATE_KEY   NUMBER(8,0)  NOT NULL,
  RATING     NUMBER(2,1)  NOT NULL,
  RATED_AT   TIMESTAMP_NTZ NOT NULL,
  LOADED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (USER_KEY, MOVIE_KEY),
  FOREIGN KEY (USER_KEY)  REFERENCES MOVIELENS.CORE.DIM_USER  (USER_KEY),
  FOREIGN KEY (MOVIE_KEY) REFERENCES MOVIELENS.CORE.DIM_MOVIE (MOVIE_KEY),
  FOREIGN KEY (DATE_KEY)  REFERENCES MOVIELENS.CORE.DIM_DATE  (DATE_KEY)
);

-- ---------- Load dimensions (idempotent: safe to re-run) ------------------------------

-- DIM_DATE: deterministic calendar, so a full overwrite is fine.
INSERT OVERWRITE INTO MOVIELENS.CORE.DIM_DATE
SELECT
  TO_NUMBER(TO_CHAR(d, 'YYYYMMDD'))  AS DATE_KEY,
  d                                  AS FULL_DATE,
  YEAR(d)                            AS CAL_YEAR,
  QUARTER(d)                         AS CAL_QUARTER,
  MONTH(d)                           AS CAL_MONTH,
  MONTHNAME(d)                       AS MONTH_NAME,
  DAY(d)                             AS DAY_OF_MONTH,
  DAYOFWEEKISO(d)                    AS DAY_OF_WEEK,
  DAYNAME(d)                         AS DAY_NAME,
  DAYOFWEEKISO(d) IN (6, 7)          AS IS_WEEKEND
FROM (
  SELECT DATEADD(DAY, SEQ4(), DATE '1995-01-01') AS d
  FROM TABLE(GENERATOR(ROWCOUNT => 20000))
)
WHERE d <= DATE '2045-12-31';

-- DIM_MOVIE: MERGE keeps surrogate keys stable across re-runs.
MERGE INTO MOVIELENS.CORE.DIM_MOVIE t
USING (SELECT MOVIE_ID, TITLE, RELEASE_YEAR FROM MOVIELENS.RAW.MOVIES) s
  ON t.MOVIE_ID = s.MOVIE_ID
WHEN MATCHED AND (t.TITLE <> s.TITLE OR NOT EQUAL_NULL(t.RELEASE_YEAR, s.RELEASE_YEAR)) THEN
  UPDATE SET TITLE = s.TITLE, RELEASE_YEAR = s.RELEASE_YEAR, UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
  INSERT (MOVIE_ID, TITLE, RELEASE_YEAR) VALUES (s.MOVIE_ID, s.TITLE, s.RELEASE_YEAR);

MERGE INTO MOVIELENS.CORE.DIM_GENRE t
USING (SELECT DISTINCT GENRE AS GENRE_NAME FROM MOVIELENS.RAW.MOVIE_GENRES) s
  ON t.GENRE_NAME = s.GENRE_NAME
WHEN NOT MATCHED THEN INSERT (GENRE_NAME) VALUES (s.GENRE_NAME);

MERGE INTO MOVIELENS.CORE.BRIDGE_MOVIE_GENRE t
USING (
  SELECT DISTINCT m.MOVIE_KEY, g.GENRE_KEY
  FROM MOVIELENS.RAW.MOVIE_GENRES rg
  JOIN MOVIELENS.CORE.DIM_MOVIE m ON m.MOVIE_ID   = rg.MOVIE_ID
  JOIN MOVIELENS.CORE.DIM_GENRE g ON g.GENRE_NAME = rg.GENRE
) s
  ON t.MOVIE_KEY = s.MOVIE_KEY AND t.GENRE_KEY = s.GENRE_KEY
WHEN NOT MATCHED THEN INSERT (MOVIE_KEY, GENRE_KEY) VALUES (s.MOVIE_KEY, s.GENRE_KEY);

-- DIM_USER and FACT_RATINGS are loaded by the incremental procedure in script 05.

SELECT 'DIM_DATE' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM MOVIELENS.CORE.DIM_DATE
UNION ALL SELECT 'DIM_MOVIE', COUNT(*) FROM MOVIELENS.CORE.DIM_MOVIE
UNION ALL SELECT 'DIM_GENRE', COUNT(*) FROM MOVIELENS.CORE.DIM_GENRE
UNION ALL SELECT 'BRIDGE_MOVIE_GENRE', COUNT(*) FROM MOVIELENS.CORE.BRIDGE_MOVIE_GENRE;
